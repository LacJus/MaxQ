use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum HostClassification {
    /// Maps a hostname that belongs to an imported proxy node in `[Proxy]` (e.g., CNAME/IP alias).
    /// Medium risk: requires user review, often necessary when `use-local-host-item-for-proxy = true`.
    ProxyEndpointAlias,
    /// Maps a strictly local/LAN hostname (`*.local`, `localhost`, `*.lan`).
    LocalDomain,
    /// Maps an arbitrary third-party domain (high risk of DNS/credential/update hijacking).
    /// Always quarantined and disabled by default.
    ThirdPartyDomainOverride,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct HostEntry {
    pub domain: String,
    pub target: String,
    pub is_ip_target: bool,
    pub classification: HostClassification,
    /// Quarantined (`false`) by default until explicitly approved by the user.
    #[serde(default)]
    pub approved: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SecuritySeverity {
    Info,
    Medium,
    High,
    Critical,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SecurityActionTaken {
    Stripped,
    Quarantined,
    Flagged,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SecurityFinding {
    pub severity: SecuritySeverity,
    pub action: SecurityActionTaken,
    pub category: String,
    pub summary: String,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub samples: Vec<String>,
    pub count: usize,
}

/// Structured report generated by `maxq-sanitizer` for every external import
/// (`.conf`, subscription, Clash YAML, or `sing-box` JSON).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
pub struct ImportSecurityReport {
    pub total_nodes_imported: usize,
    pub metadata_nodes_count: usize,
    pub insecure_nodes_count: usize,
    pub pending_pin_bootstrap_count: usize,
    pub total_rules_imported: usize,
    pub unsupported_rules_count: usize,
    pub quarantined_hosts_count: usize,
    pub stripped_sections: Vec<String>,
    pub findings: Vec<SecurityFinding>,
}

impl ImportSecurityReport {
    pub fn has_high_or_critical(&self) -> bool {
        self.findings.iter().any(|f| {
            matches!(
                f.severity,
                SecuritySeverity::High | SecuritySeverity::Critical
            )
        })
    }
}
